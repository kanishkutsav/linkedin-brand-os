-- Minimal daily activity rollup. One row per user per UTC day; no page or content data is stored.
CREATE TABLE IF NOT EXISTS public.user_activity_days (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.auth_users(id) ON DELETE CASCADE,
    activity_date DATE NOT NULL,
    last_active_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_user_activity_days_user_date UNIQUE (user_id, activity_date)
);

CREATE INDEX IF NOT EXISTS idx_user_activity_days_user_date
    ON public.user_activity_days (user_id, activity_date DESC);
CREATE INDEX IF NOT EXISTS idx_user_activity_days_last_active
    ON public.user_activity_days (last_active_at DESC);

ALTER TABLE public.user_activity_days ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_activity_days FROM anon, authenticated;
GRANT ALL ON TABLE public.user_activity_days TO service_role;

-- Preserve login counts after auth_sessions are deleted on logout.
ALTER TABLE public.user_activity_days
    ADD COLUMN IF NOT EXISTS login_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.user_activity_days
    ADD COLUMN IF NOT EXISTS first_login_at TIMESTAMPTZ;
ALTER TABLE public.user_activity_days
    ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;

-- Backfill only sessions that still exist at rollout. Older logged-out sessions
-- are not recoverable because auth_sessions are intentionally deleted on logout.
INSERT INTO public.user_activity_days (
    user_id, activity_date, last_active_at, login_count, first_login_at, last_login_at
)
SELECT
    user_id,
    (created_at AT TIME ZONE 'UTC')::date,
    MAX(created_at),
    COUNT(*)::INTEGER,
    MIN(created_at),
    MAX(created_at)
FROM public.auth_sessions
GROUP BY user_id, (created_at AT TIME ZONE 'UTC')::date
ON CONFLICT (user_id, activity_date) DO NOTHING;
